-- Extends the original structure.sql. Existing tables/columns are untouched;
-- new columns on existing tables are NULLable so old rows stay valid.

ALTER TABLE dbo.UNIVERSITIES ADD
    NAME      NVARCHAR(200) NULL,
    LOGO_PATH NVARCHAR(260) NULL;
GO

ALTER TABLE dbo.FACULTY ADD
    NAME  NVARCHAR(200) NULL,
    THEME VARCHAR(20)   NULL,
    ICON  VARCHAR(60)   NULL;
GO

ALTER TABLE dbo.MAJOR ADD
    NAME  NVARCHAR(200) NULL,
    THEME VARCHAR(20)   NULL,
    ICON  VARCHAR(60)   NULL;
GO

ALTER TABLE dbo.COURSE ADD
    NAME        NVARCHAR(200) NULL,
    SEMESTER    VARCHAR(5)    NULL,
    COURSE_TYPE VARCHAR(20)   NULL,
    LECTURER    NVARCHAR(100) NULL,
    UPDATED     DATE          NULL,
    COLOR       VARCHAR(20)   NULL;
GO

CREATE TABLE dbo.DOCUMENT (
    DOCUMENT_ID  VARCHAR(50)    NOT NULL,
    COURSE_ID    VARCHAR(30)    NOT NULL,
    TITLE        NVARCHAR(300)  NOT NULL,
    [DESCRIPTION] NVARCHAR(MAX) NULL,
    [TYPE]       VARCHAR(10)    NOT NULL CONSTRAINT DF_Document_Type DEFAULT 'FILE',
    MIME_TYPE    VARCHAR(100)   NULL,
    LECTURER     NVARCHAR(100)  NULL,
    UPDATED      DATE           NULL,
    SIZE_BYTES   BIGINT         NULL,
    [VIEWS]      INT            NOT NULL CONSTRAINT DF_Document_Views DEFAULT 0,
    IS_MASTER    BIT            NOT NULL CONSTRAINT DF_Document_Master DEFAULT 0,
    FILE_PATH    NVARCHAR(500)  NULL,
    PREVIEW_PATH NVARCHAR(500)  NULL,
    CONSTRAINT PK_Document PRIMARY KEY (DOCUMENT_ID),
    CONSTRAINT FK_Document_Course FOREIGN KEY (COURSE_ID)
        REFERENCES dbo.COURSE (COURSE_ID)
);
GO

CREATE INDEX IX_Document_Course ON dbo.DOCUMENT (COURSE_ID);
GO

CREATE TABLE dbo.USERS (
    USER_ID       INT IDENTITY(1,1) NOT NULL,
    EMAIL         NVARCHAR(254)     NOT NULL,
    DISPLAY_NAME  NVARCHAR(100)     NULL,
    PASSWORD_HASH VARCHAR(255)      NULL,
    CREATED_AT    DATETIME2         NOT NULL CONSTRAINT DF_Users_Created DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_Users PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_Users_Email UNIQUE (EMAIL)
);
GO

CREATE TABLE dbo.SAVED_DOCUMENT (
    USER_ID     INT         NOT NULL,
    DOCUMENT_ID VARCHAR(50) NOT NULL,
    SAVED_AT    DATETIME2   NOT NULL CONSTRAINT DF_Saved_At DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_SavedDocument PRIMARY KEY (USER_ID, DOCUMENT_ID),
    CONSTRAINT FK_Saved_User FOREIGN KEY (USER_ID) REFERENCES dbo.USERS (USER_ID),
    CONSTRAINT FK_Saved_Document FOREIGN KEY (DOCUMENT_ID) REFERENCES dbo.DOCUMENT (DOCUMENT_ID)
);
GO
