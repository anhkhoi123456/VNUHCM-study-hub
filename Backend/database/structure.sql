-- SQL Server: run once in SSMS or sqlcmd against an empty VNUHCM database.
IF DB_ID(N'VNUHCM') IS NULL
    EXEC(N'CREATE DATABASE [VNUHCM]');
GO

USE [VNUHCM];
GO

-- A container row links a parent to one child. The child-side UNIQUE
-- constraint enforces one parent per faculty, major, or course.
CREATE TABLE dbo.UNIVERSITIES (
    UNIVERSITY_ID VARCHAR(5) NOT NULL,
    CONSTRAINT PK_Universities PRIMARY KEY (UNIVERSITY_ID)
);

CREATE TABLE dbo.FACULTY (
    FACULTY_ID VARCHAR(10) NOT NULL,
    CONSTRAINT PK_Faculty PRIMARY KEY (FACULTY_ID)
);

CREATE TABLE dbo.MAJOR (
    MAJOR_ID VARCHAR(15) NOT NULL,
    CONSTRAINT PK_Major PRIMARY KEY (MAJOR_ID)
);

CREATE TABLE dbo.COURSE (
    COURSE_ID VARCHAR(30) NOT NULL,
    CONSTRAINT PK_Course PRIMARY KEY (COURSE_ID)
);

CREATE TABLE dbo.FACULTY_CONTAINER (
    UNIVERSITY_ID VARCHAR(5) NOT NULL,
    FACULTY_ID VARCHAR(10) NOT NULL,
    CONSTRAINT PK_FacultyContainer PRIMARY KEY (UNIVERSITY_ID, FACULTY_ID),
    CONSTRAINT UQ_FacultyContainer_Faculty UNIQUE (FACULTY_ID),
    CONSTRAINT FK_FacultyContainer_University FOREIGN KEY (UNIVERSITY_ID)
        REFERENCES dbo.UNIVERSITIES (UNIVERSITY_ID),
    CONSTRAINT FK_FacultyContainer_Faculty FOREIGN KEY (FACULTY_ID)
        REFERENCES dbo.FACULTY (FACULTY_ID)
);

CREATE TABLE dbo.MAJOR_CONTAINER (
    FACULTY_ID VARCHAR(10) NOT NULL,
    MAJOR_ID VARCHAR(15) NOT NULL,
    CONSTRAINT PK_MajorContainer PRIMARY KEY (FACULTY_ID, MAJOR_ID),
    CONSTRAINT UQ_MajorContainer_Major UNIQUE (MAJOR_ID),
    CONSTRAINT FK_MajorContainer_Faculty FOREIGN KEY (FACULTY_ID)
        REFERENCES dbo.FACULTY (FACULTY_ID),
    CONSTRAINT FK_MajorContainer_Major FOREIGN KEY (MAJOR_ID)
        REFERENCES dbo.MAJOR (MAJOR_ID)
);

CREATE TABLE dbo.COURSE_CONTAINER (
    MAJOR_ID VARCHAR(15) NOT NULL,
    COURSE_ID VARCHAR(30) NOT NULL,
    CONSTRAINT PK_CourseContainer PRIMARY KEY (MAJOR_ID, COURSE_ID),
    CONSTRAINT UQ_CourseContainer_Course UNIQUE (COURSE_ID),
    CONSTRAINT FK_CourseContainer_Major FOREIGN KEY (MAJOR_ID)
        REFERENCES dbo.MAJOR (MAJOR_ID),
    CONSTRAINT FK_CourseContainer_Course FOREIGN KEY (COURSE_ID)
        REFERENCES dbo.COURSE (COURSE_ID)
);
